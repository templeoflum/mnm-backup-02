"""Guard — the launched visualizer must build file paths the SHORT way ({digit}.{triad}),
matching server.resolve(). Bug-born: addrPath drifted to the full long form after the
address-shorten rename and 404'd every open-a-file (incident.rename-missed-addrpath, 221).

A net, not a gate: it catches a client path-builder diverging from resolve()'s format —
the class a literal git-grep can't see, because the long form is GENERATED by template.

    python test_visualizer_paths.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def launched_visualizer():
    """The .html file lattice.bat opens — the live visualizer."""
    bat = (ROOT / 'lattice.bat').read_text(encoding='utf-8', errors='replace')
    m = re.search(r'URL=http://[^/]+/(\S+\.html)', bat)
    assert m, 'lattice.bat: no launched .html URL found'
    rel = m.group(1).strip().strip('"')
    return ROOT / rel


def addrpath_body(html):
    """The body window of function addrPath(...) — the file-open path builder."""
    i = html.find('function addrPath(')
    assert i != -1, 'addrPath() not found in the visualizer'
    return html[i:i + 600]


def main():
    vis = launched_visualizer()
    assert vis.exists(), f'launched visualizer not on disk: {vis}'
    body = addrpath_body(vis.read_text(encoding='utf-8', errors='replace'))

    fails = []
    if 'TRIADS[sub]' not in body:
        fails.append('addrPath does not use TRIADS[sub] (the short folder name)')
    for tok in ('a.role', 'a.mode', 'a.register', 'a.ratio'):
        if tok in body:
            fails.append(f'addrPath injects the long form (found `{tok}`) — folders are {{digit}}.{{triad}} since the rename')
            break

    if fails:
        print('FAIL · visualizer builds wrong file paths:')
        for f in fails:
            print('  -', f)
        print(f'  (checked {vis.relative_to(ROOT)})')
        sys.exit(1)
    print(f'PASS · {vis.name} addrPath builds short {{digit}}.{{triad}} paths (= server.resolve())')


if __name__ == '__main__':
    main()
